"""Telemetry, baselines and simulation control endpoints."""
from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy import select
from sqlalchemy.orm import Session

from .. import simulation
from ..database import get_db
from ..models import AstronautProfile, HealthBaseline, Mission, MissionAssignment, User
from ..reference import REFERENCE_RANGES
from ..security import (
    audit,
    ensure_astronaut_access,
    ensure_mission_access,
    get_current_user,
    require_roles,
)
from ..serializers import snapshot_out
from ..services import intelligence

router = APIRouter(prefix="/api", tags=["monitoring"])


def _crew_profiles(mission_id: int, db: Session) -> list[AstronautProfile]:
    return list(
        db.scalars(
            select(AstronautProfile)
            .join(MissionAssignment, MissionAssignment.user_id == AstronautProfile.user_id)
            .where(MissionAssignment.mission_id == mission_id)
        ).all()
    )


@router.get("/telemetry/latest")
def latest_all(
    mission_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    ensure_mission_access(user, mission_id, db)
    rows = []
    for profile in _crew_profiles(mission_id, db):
        snap = simulation.latest_snapshot(db, profile.id)
        rows.append(
            {
                "astronaut_id": profile.id,
                "callsign": profile.callsign,
                "name": profile.user.full_name if profile.user else "",
                "latest": snapshot_out(snap),
            }
        )
    return {
        "mission_id": mission_id,
        "crew": rows,
        "source": "simulated",
        "disclaimer": "All values are generated by the deterministic simulation engine. They are not astronaut measurements.",
    }


@router.get("/telemetry")
def telemetry(
    astronaut_id: int,
    mission_id: int | None = None,
    limit: int = 300,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    profile = db.get(AstronautProfile, astronaut_id)
    if not profile:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Astronaut not found")
    ensure_astronaut_access(user, profile, db)
    rows = simulation.snapshot_history(db, astronaut_id, mission_id, limit=min(limit, 1000))
    return {
        "astronaut_id": astronaut_id,
        "series": [snapshot_out(r) for r in rows],
        "source": "simulated",
    }


@router.get("/baselines")
def baselines(
    astronaut_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    profile = db.get(AstronautProfile, astronaut_id)
    if not profile:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Astronaut not found")
    ensure_astronaut_access(user, profile, db)
    rows = list(
        db.scalars(select(HealthBaseline).where(HealthBaseline.astronaut_id == astronaut_id)).all()
    )
    return {
        "baselines": [
            {"metric": b.metric, "value": b.value, "unit": b.unit, "method": b.method, "note": b.note}
            for b in rows
        ],
        "reference_ranges": REFERENCE_RANGES,
    }


@router.post("/telemetry/simulate")
def simulate_tick(
    mission_id: int,
    request: Request,
    user: User = Depends(require_roles("admin", "mission_control", "medical")),
    db: Session = Depends(get_db),
):
    """Append one fresh simulated sample per crew member and re-run analysis."""
    mission = db.get(Mission, mission_id)
    if not mission:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Mission not found")
    if user.role != "admin":
        ensure_mission_access(user, mission_id, db)
    from .missions import scenario_config

    seed, cfg = scenario_config(db, mission_id)
    created = simulation.append_latest(db, mission, seed, cfg)
    results = []
    for snap in created:
        profile = db.get(AstronautProfile, snap.astronaut_id)
        if profile:
            outcome = intelligence.refresh_intelligence(db, profile, mission, create_incidents=True)
            results.append(
                {
                    "astronaut_id": profile.id,
                    "incidents_created": outcome["incidents_created"],
                    "top_signal": outcome["signals"][0] if outcome["signals"] else None,
                }
            )
    audit(db, user, "telemetry.simulate", "mission", mission_id, f"n={len(created)}", request)
    return {
        "ok": True,
        "samples": len(created),
        "results": results,
        "source": "simulated",
    }
